import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const readmePath = resolve(root, 'README.md');
const outputPath = resolve(root, 'CHANGELOG.md');
const timestampsPath = resolve(root, 'src/data/catalog-added-at.json');
const check = process.argv.includes('--check');
const markdown = readFileSync(readmePath, 'utf8');
const inclusionDates = JSON.parse(readFileSync(timestampsPath, 'utf8'));
const normalizeUrl = (url) => url.toLowerCase().replace(/\.git\/?$/, '').replace(/\/$/, '');
const categoryHeadings = [...markdown.matchAll(/^### (.+?)(?: \((\d+)\)|（(\d+)）)$/gm)].slice(0, 11);

const entries = categoryHeadings.flatMap((heading, categoryIndex) => {
  const start = heading.index ?? 0;
  const headingEnd = start + heading[0].length;
  const nextHeadingOffset = markdown.slice(headingEnd).search(/^### /m);
  const end = nextHeadingOffset === -1 ? markdown.length : headingEnd + nextHeadingOffset;
  return markdown.slice(start, end).split(/\r?\n/)
    .filter((line) => line.startsWith('| [') && line.includes('https://github.com/'))
    .map((line) => {
      const cells = line.slice(1, -1).split('|').map((cell) => cell.trim());
      const link = cells[0]?.match(/^\[([^\]]+)\]\((https:\/\/github\.com\/[^)]+)\)$/);
      if (!link || cells.length !== 5) throw new Error(`Unable to parse catalog row: ${line}`);
      const addedAt = inclusionDates[normalizeUrl(link[2])];
      if (!addedAt) throw new Error(`Missing inclusion timestamp for ${link[2]}`);
      if (cells[3] !== addedAt.slice(0, 10)) throw new Error(`Inclusion date mismatch for ${link[2]}`);
      return {
        name: link[1],
        url: link[2],
        stars: cells[1],
        language: cells[2],
        date: cells[3],
        description: cells[4],
        category: heading[1],
        categoryIndex,
      };
    });
});

const days = [...Map.groupBy(entries, (entry) => entry.date).entries()].sort(([left], [right]) => right.localeCompare(left));
const lines = [
  '# Changelog',
  '',
  'Daily additions to the Awesome Jev catalog. This file is generated from the verified catalog and `src/data/catalog-added-at.json`.',
  '',
  '> Do not edit this file by hand. Run `npm run sync:changelog` after updating the catalog.',
  '',
];

for (const [date, dayEntries] of days) {
  lines.push(`## ${date} — ${dayEntries.length} project${dayEntries.length === 1 ? '' : 's'}`, '');
  const categories = [...Map.groupBy(dayEntries, (entry) => entry.category).entries()]
    .sort(([, leftEntries], [, rightEntries]) => leftEntries[0].categoryIndex - rightEntries[0].categoryIndex);
  for (const [category, categoryEntries] of categories) {
    lines.push(`### ${category} (${categoryEntries.length})`, '');
    for (const entry of categoryEntries) {
      lines.push(`- [${entry.name}](${entry.url}) — ${entry.description} _${entry.language}; ${entry.stars}._`);
    }
    lines.push('');
  }
}

const generated = `${lines.join('\n').trim()}\n`;
if (check) {
  const current = readFileSync(outputPath, 'utf8').replace(/\r\n/g, '\n');
  if (current !== generated) {
    console.error('CHANGELOG.md is out of date. Run npm run sync:changelog.');
    process.exit(1);
  }
  console.log(`CHANGELOG.md is current (${entries.length} projects across ${days.length} days).`);
} else {
  writeFileSync(outputPath, generated);
  console.log(`Generated CHANGELOG.md with ${entries.length} projects across ${days.length} days.`);
}
